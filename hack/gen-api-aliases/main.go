// Command gen-api-aliases generates deprecation shims for packages that moved into the nested
// api module (github.com/argoproj/argo-cd/api/v3).
//
// For every package under api/, it writes a file at the package's original path in the root
// module that re-exports the moved package's exported identifiers. Existing consumers therefore
// keep compiling against the old import paths for one release cycle.
//
// Types are re-exported as aliases (type X = api.X), so their methods, and type identity, come
// along unchanged: a *v1alpha1.Application obtained through a shim is the same type as one
// obtained from the api module, and can be passed between the two freely.
//
// Two things aliases cannot carry, both of which are documented in the migration notes:
//
//   - Methods removed from a type. Go rejects declaring methods on a non-local type, so the
//     credential constructors that moved off Repository in favour of util/repocreds cannot be
//     restored here.
//   - Variables. A var is re-exported as `var X = api.X`, which copies the value at init. That is
//     fine for the read-only values in these packages, but a consumer mutating one through the
//     shim would not affect the api module's copy.
//
// Usage: go run ./hack/gen-api-aliases
package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	apiModulePath = "github.com/argoproj/argo-cd/api/v3"
	apiDir        = "api"
	generatedFile = "zz_generated_aliases.go"
)

type exports struct {
	pkgName string
	types   []string
	consts  []string
	vars    []string // vars and funcs; both are re-exported as vars
}

func main() {
	root, err := os.Getwd()
	if err != nil {
		fail(err)
	}
	// Allow running from anywhere inside the repo.
	for root != "/" {
		if _, err := os.Stat(filepath.Join(root, "go.mod")); err == nil {
			if _, err := os.Stat(filepath.Join(root, apiDir, "go.mod")); err == nil {
				break
			}
		}
		root = filepath.Dir(root)
	}

	var written, skipped int
	err = filepath.WalkDir(filepath.Join(root, apiDir), func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		rel, err := filepath.Rel(filepath.Join(root, apiDir), path)
		if err != nil {
			return err
		}
		if rel == "." || strings.HasPrefix(rel, "api-rules") {
			return nil
		}
		ex, err := collect(path)
		if err != nil {
			return err
		}
		if ex == nil || ex.total() == 0 {
			skipped++
			return nil
		}
		if err := write(root, rel, ex); err != nil {
			return err
		}
		written++
		return nil
	})
	if err != nil {
		fail(err)
	}
	fmt.Printf("gen-api-aliases: wrote %d shim packages (%d packages had nothing to re-export)\n", written, skipped)
}

func (e *exports) total() int { return len(e.types) + len(e.consts) + len(e.vars) }

// collect parses the non-test Go files in dir and records its exported declarations.
func collect(dir string) (*exports, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	var ex *exports
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, 0)
		if err != nil {
			return nil, err
		}
		if ex == nil {
			ex = &exports{pkgName: f.Name.Name}
		} else if f.Name.Name != ex.pkgName {
			// Shouldn't happen in this tree, but don't silently mix packages.
			return nil, fmt.Errorf("%s: package %q does not match %q", dir, f.Name.Name, ex.pkgName)
		}
		for _, decl := range f.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				// Methods travel with their receiver's type alias.
				if d.Recv == nil && d.Name.IsExported() {
					ex.vars = append(ex.vars, d.Name.Name)
				}
			case *ast.GenDecl:
				for _, spec := range d.Specs {
					switch sp := spec.(type) {
					case *ast.TypeSpec:
						if sp.Name.IsExported() {
							ex.types = append(ex.types, sp.Name.Name)
						}
					case *ast.ValueSpec:
						for _, n := range sp.Names {
							if !n.IsExported() {
								continue
							}
							if d.Tok == token.CONST {
								ex.consts = append(ex.consts, n.Name)
							} else {
								ex.vars = append(ex.vars, n.Name)
							}
						}
					}
				}
			}
		}
	}
	if ex == nil {
		return nil, nil
	}
	sort.Strings(ex.types)
	sort.Strings(ex.consts)
	sort.Strings(ex.vars)
	return ex, nil
}

func write(root, rel string, ex *exports) error {
	outDir := filepath.Join(root, rel)
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	importPath := apiModulePath + "/" + filepath.ToSlash(rel)

	var b strings.Builder
	b.WriteString("// Code generated by hack/gen-api-aliases. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "// Package %s re-exports %s.\n//\n", ex.pkgName, importPath)
	fmt.Fprintf(&b, "// Deprecated: this package moved to %s. This shim keeps the old import path\n", importPath)
	b.WriteString("// working for one release cycle and will be removed in the next major version. Import\n")
	fmt.Fprintf(&b, "// %s instead.\n", importPath)
	fmt.Fprintf(&b, "package %s\n\n", ex.pkgName)
	fmt.Fprintf(&b, "import api %q\n\n", importPath)

	if len(ex.types) > 0 {
		b.WriteString("// Type aliases, so methods and type identity are preserved.\ntype (\n")
		for _, n := range ex.types {
			fmt.Fprintf(&b, "\t%s = api.%s\n", n, n)
		}
		b.WriteString(")\n\n")
	}
	if len(ex.consts) > 0 {
		b.WriteString("const (\n")
		for _, n := range ex.consts {
			fmt.Fprintf(&b, "\t%s = api.%s\n", n, n)
		}
		b.WriteString(")\n\n")
	}
	if len(ex.vars) > 0 {
		b.WriteString("var (\n")
		for _, n := range ex.vars {
			fmt.Fprintf(&b, "\t%s = api.%s\n", n, n)
		}
		b.WriteString(")\n")
	}

	return os.WriteFile(filepath.Join(outDir, generatedFile), []byte(b.String()), 0o644)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen-api-aliases:", err)
	os.Exit(1)
}
